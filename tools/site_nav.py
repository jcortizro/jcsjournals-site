# THE ONE SITE MENU for every page in the JC's Journals family (JC, 26 Oct 2026: "all of the websites that are a part
# of the jcsjournals.com web need to have the top part ... free resource library, free recipe book, and then it needs
# to say free course. And the free course sends them to jcsjournals.com").
#
# This file is the only place the menu is written. Everything else imports it:
#   tools/build-td101-page.py  -> jcsjournals.com (jcj/) and td101.carrd.co (td101page/), current item = Free Course
#   tools/add-site-nav.py      -> freelibrary.carrd.co (library/) and freerecipes.carrd.co (recipebook/)
#   tools/check-site-nav.py    -> fails the build unless every page carries exactly this menu
# Change a link, a word or a colour HERE, then run tools/build-all.ps1. Never edit the copies in the pages.
#
# What it looks like (unchanged from the jcsjournals.com bar JC approved on 25 Oct 2026): "JC's Journals | FREE
# RESOURCES ->" and the three lines. Tapping opens a panel from the right with the three free sites, then a Socials
# button that opens Facebook, YouTube, Instagram and Substack in a new tab. The X, the dark backdrop and Escape close
# it. The site you are on is marked (aria-current="page": gold outline, a faint gold tint and a gold bar on its left
# edge, nothing that takes width, so its label wraps exactly like the others); tapping it closes the menu and scrolls
# to the top instead of reloading. No #hash links anywhere: Carrd hijacks them.
#
# Why it does not borrow anything from the page it sits on: the three hosts have different CSS (the library and the
# recipe book style every <a> and <button>; the old recipe pieces have no Montserrat at all), so every rule here is
# scoped to the menu's own ids and declares its own colours, fonts and sizes.
#   Sizes: the course bar was written in rem, and every Carrd shell sets the root size in steps (18pt, 13pt at
#   <=1680px, 11pt at <=980px; measured on all four live shells, 26 Oct 2026). So the menu carries that ladder as its
#   own unit (--jsn-u) and stays the same size on any host, Carrd or not.
#   Fonts: the private families below point at the exact Google files the course page already loads (Montserrat v31,
#   the same bytes as the copy embedded in the library, sha256 06b16db7...; Source Sans 3 v20), so the browser fetches
#   each file once and every host draws the same letters. The host's own Montserrat is the fallback.

SITES = [  # (key, url, label), in panel order. Same tab, never a #hash.
    ("library", "https://freelibrary.carrd.co/", "Free Resource Library"),
    ("recipes", "https://freerecipes.carrd.co/", "Free Recipe Book"),
    ("course", "https://jcsjournals.com/", "Free Course"),
]
SOCIALS = [  # (url, label), in panel order. New tab, rel=noopener. Handles: memory jc-social-handles-changed.
    ("https://www.facebook.com/jc.ortiz.roman/", "Facebook"),
    ("https://www.youtube.com/@jc_ortiz_roman", "YouTube"),
    ("https://www.instagram.com/jc.ortiz.roman/", "Instagram"),
    ("https://jcortizroman.substack.com/", "Substack"),
]
BRAND = "JC's Journals"
LABEL = "Free resources"
KEYS = [k for k, _, _ in SITES]

HTML_START = "<!-- jcj-sitenav:start (generated by tools/site_nav.py; edit it there, never here) -->"
HTML_END = "<!-- jcj-sitenav:end -->"
CODE_START = "/* jcj-sitenav:start (generated by tools/site_nav.py; edit it there, never here) */"
CODE_END = "/* jcj-sitenav:end */"

_X = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 6l12 12M18 6L6 18"/></svg>'
_CHEV = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>'
_ARROW = '<svg class="jsn-arrow" viewBox="0 0 24 24" aria-hidden="true"><path d="M4 12h15M13 6l6 6-6 6"/></svg>'


def nav_html(current):
    """The menu markup for one site. current = the key of the site this copy lives on."""
    if current not in KEYS:
        raise ValueError("site_nav: unknown current site %r (want one of %s)" % (current, KEYS))
    lines = [
        '<div class="jsn-bar" id="jcj-navbar">',
        '  <div class="jsn-in">',
        '    <span class="jsn-brand">%s</span>' % BRAND,
        '    <button class="jsn-btn" type="button" aria-expanded="false" aria-controls="jcj-menu">',
        '      <span class="jsn-sep" aria-hidden="true"></span>',
        '      <span class="jsn-label">%s</span>' % LABEL,
        '      ' + _ARROW,
        '      <span class="jsn-burger" aria-hidden="true"><i></i><i></i><i></i></span>',
        '    </button>',
        '  </div>',
        '</div>',
        '<div class="jsn-scrim" id="jcj-navscrim" data-jsn-close></div>',
        '<nav class="jsn-panel" id="jcj-menu" aria-label="%s">' % LABEL,
        '  <div class="jsn-head">',
        '    <span class="jsn-title">%s</span>' % LABEL,
        '    <button class="jsn-close" type="button" aria-label="Close menu" data-jsn-close>' + _X + '</button>',
        '  </div>',
    ]
    for key, url, label in SITES:
        cur = ' aria-current="page"' if key == current else ''
        lines.append('  <a class="jsn-link" href="%s"%s>%s</a>' % (url, cur, label))
    lines += [
        '  <button class="jsn-link jsn-soc" type="button" aria-expanded="false" aria-controls="jcj-socials">Socials'
        + _CHEV + '</button>',
        '  <div class="jsn-sub" id="jcj-socials" hidden>',
    ]
    for url, label in SOCIALS:
        lines.append('    <a href="%s" target="_blank" rel="noopener">%s</a>' % (url, label))
    lines += ['  </div>', '</nav>']
    return "\n".join(lines)


def html_block(current):
    """Markup between the start/end comments. Used where the page's CSS and JS live in separate files."""
    return HTML_START + "\n" + nav_html(current) + "\n" + HTML_END


def inline_block(current):
    """Markup plus its own <style> and <script>, for a page that is one HTML file (the recipe book's index.html)."""
    return (HTML_START + "\n<style>\n" + NAV_CSS.strip("\n") + "\n</style>\n" + nav_html(current)
            + "\n<script>\n" + NAV_JS.strip("\n") + "\n</script>\n" + HTML_END)


def css_block():
    return CODE_START + "\n" + NAV_CSS.strip("\n") + "\n" + CODE_END


def js_block():
    return CODE_START + "\n" + NAV_JS.strip("\n") + "\n" + CODE_END


def text_nodes():
    """Every visible text node of the menu, in page order (the course build's text gate counts these)."""
    return [BRAND, LABEL, LABEL] + [t for _, _, t in SITES] + ["Socials"] + [t for _, t in SOCIALS]


