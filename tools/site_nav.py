NAV_JS = r"""/* Site menu (tools/site_nav.py), the same on jcsjournals.com, td101.carrd.co, freelibrary and freerecipes.
   Block comments only: Carrd flattens embed code to one line. Runs once, whenever the page's script runs. */
(function(){
  function init(){
    var root=document.documentElement;
    var bar=document.getElementById('jcj-navbar');
    var panel=document.getElementById('jcj-menu');
    if(!bar||!panel||bar.getAttribute('data-jsn-ready')==='1')return;
    var btn=bar.querySelector('.jsn-btn');
    if(!btn)return;
    bar.setAttribute('data-jsn-ready','1');
    function isOpen(){return root.classList.contains('jcj-nav-open');}
    function setOpen(on){
      root.classList.toggle('jcj-nav-open',on);
      btn.setAttribute('aria-expanded',on?'true':'false');
      var target=on?panel.querySelector('.jsn-close'):btn;
      if(target)try{target.focus({preventScroll:true});}catch(e){}
    }
    btn.addEventListener('click',function(){setOpen(!isOpen());});
    Array.prototype.forEach.call(document.querySelectorAll('[data-jsn-close]'),function(el){
      el.addEventListener('click',function(){setOpen(false);});
    });
    document.addEventListener('keydown',function(e){if(e.key==='Escape'&&isOpen())setOpen(false);});
    var soc=panel.querySelector('.jsn-soc'),sub=document.getElementById('jcj-socials');
    if(soc&&sub)soc.addEventListener('click',function(){
      var on=soc.getAttribute('aria-expanded')!=='true';
      soc.setAttribute('aria-expanded',on?'true':'false');
      sub.hidden=!on;
    });
    /* The site you are on: close the menu and go to the top instead of reloading. Instant, because Carrd
       interrupts a long smooth scroll (measured on the library, 2026-09). */
    var here=panel.querySelector('.jsn-link[aria-current="page"]');
    if(here)here.addEventListener('click',function(e){
      e.preventDefault();
      setOpen(false);
      var de=document.documentElement,prev=de.style.scrollBehavior;
      de.style.scrollBehavior='auto';
      window.scrollTo(0,0);
      de.style.scrollBehavior=prev;
    });
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);else init();
})();
"""


